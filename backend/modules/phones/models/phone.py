import uuid
from datetime import datetime
from decimal import Decimal

from sqlalchemy import UUID, CheckConstraint, DateTime, Enum, Integer, Numeric, String, Text, func, text
from sqlalchemy.orm import Mapped, mapped_column

from modules.phones.database import PhonesBase

PHONE_OS = ("ios", "android")
PHONE_CONDITIONS = ("like_new", "average", "for_repair")
MODEL_CODE_MAX_LENGTH = 64
MODEL_NAME_MAX_LENGTH = 200


class Phone(PhonesBase):
    """`phones` table, one listing: docs/backend/SCHEMAS.md#phones-modulesphones."""

    __tablename__ = "phones"
    __table_args__ = (CheckConstraint("price > 0", name="ck_phones_price_positive"),)

    # The id is generated by PostgreSQL only.
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    # `users.id`, no foreign key between modules: docs/backend/SCHEMAS.md#migrations.
    user_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), index=True)
    model_code: Mapped[str] = mapped_column(String(MODEL_CODE_MAX_LENGTH))
    model_name: Mapped[str] = mapped_column(String(MODEL_NAME_MAX_LENGTH))
    os: Mapped[str] = mapped_column(Enum(*PHONE_OS, name="phone_os"))
    camera_megapixels: Mapped[int] = mapped_column(Integer)
    battery_capacity: Mapped[int] = mapped_column(Integer)
    display_size: Mapped[Decimal] = mapped_column(Numeric(4, 2))
    description: Mapped[str] = mapped_column(Text)
    condition: Mapped[str] = mapped_column(Enum(*PHONE_CONDITIONS, name="phone_condition"))
    condition_note: Mapped[str] = mapped_column(Text)
    price: Mapped[int] = mapped_column(Integer)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
